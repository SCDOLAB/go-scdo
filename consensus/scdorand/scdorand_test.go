func TestGoldenArchive(t *testing.T) {
	for _, line := range strings.Split(strings.TrimSpace(golden), "\n") {
		fields := strings.Fields(line)
		variant := fields[0]
		seed, err := strconv.ParseInt(fields[1], 10, 64)
		if err != nil {
			t.Fatal(err)
		}
		var src Source
		if variant == "emery" {
			src = NewSource_EmeryFork(seed)
		} else {
			src = NewSource(seed)
		}
		rng := NewRandObj(src)
		got := fmt.Sprintf("%s %d", variant, seed)
		for i := 0; i < 8; i++ {
			got += fmt.Sprintf(" %d", rng.Int63n(1<<63-1))
		}
		got += " |"
		for i := 0; i < 12; i++ {
			got += fmt.Sprintf(" %d", rng.Int63n(3))
		}
		if got != line {
			t.Fatalf("seed sequence mismatch\n got %s\nwant %s", got, line)
		}
	}
}
